from __future__ import annotations

import json
import re
import unicodedata
from collections import Counter

_CTRL = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]")
_MANY_BLANKS = re.compile(r"\n{4,}")
_LETTER = re.compile(r"[^\W\d_]")
_NOT_ALNUM = re.compile(r"[\W_]+")
_HANGUL = re.compile(r"[가-힣ᄀ-ᇿ㄰-㆏]")
_EN_STOPWORDS = {"the", "be", "to", "of", "and", "that", "have", "with"}
_GENERATED = ("auto-generated", "autogenerated", "automatically generated", "generated by", "do not edit")
_DATA_EXT = {"json", "csv", "tsv", "xml", "yaml", "yml", "svg", "lock", "txt"}
_FENCE_LANG = re.compile(r"[^\w+#.-]")

PROFILES: dict[str, dict] = {"web": dict(min_chars=200, max_chars=1_000_000, words=(50, 100_000), mean_word=(3, 10), max_symbols=0.1, max_ellipsis_lines=0.3, max_bullet_lines=0.9, max_dup_chars=0.2, min_alpha_words=0.8, stopwords=2),
                             "ko_web": dict(min_chars=100, max_chars=1_000_000, words=(20, 100_000), max_symbols=0.1, max_ellipsis_lines=0.3, max_bullet_lines=0.9, max_dup_chars=0.2, min_alpha_words=0.7, min_hangul=0.5), "curated": dict(min_chars=50, max_chars=5_000_000, max_dup_chars=0.5), "code": dict(min_chars=20, max_chars=1_000_000, max_line=1000, max_avg_line=100, min_alnum=0.25, max_data_file=50_000)}


def normalize(text: str, profile: str) -> str:
    text = unicodedata.normalize("NFC", text).replace("\r\n", "\n").replace("\r", "\n")
    text = _CTRL.sub("", text)
    if profile != "code":
        text = _MANY_BLANKS.sub("\n\n\n", text).strip()
    return text


def dup_line_char_frac(lines: list[str]) -> float:
    counts = Counter(lines)
    dup = sum(len(line) * (c - 1) for line, c in counts.items() if c > 1)
    return dup / max(1, sum(map(len, lines)))


def text_reason(text: str, p: dict) -> str | None:
    n = len(text)
    if n < p["min_chars"]:
        return "too_short"
    if n > p["max_chars"]:
        return "too_long"
    words = text.split()
    if "words" in p and not p["words"][0] <= len(words) <= p["words"][1]:
        return "word_count"
    if "mean_word" in p:
        mean = sum(map(len, words)) / max(1, len(words))
        if not p["mean_word"][0] <= mean <= p["mean_word"][1]:
            return "mean_word_len"
    if "max_symbols" in p and (text.count("#") + text.count("...") + text.count("…")) / max(1, len(words)) > p["max_symbols"]:
        return "symbols"
    lines = [line for line in text.split("\n") if line.strip()]
    if lines:
        if "max_ellipsis_lines" in p and sum(l.rstrip().endswith(("...", "…")) for l in lines) / len(lines) > p["max_ellipsis_lines"]:
            return "ellipsis_lines"
        if "max_bullet_lines" in p and sum(l.lstrip().startswith(("•", "-", "*", "·", "●")) for l in lines) / len(lines) > p["max_bullet_lines"]:
            return "bullet_lines"
        if dup_line_char_frac(lines) > p["max_dup_chars"]:
            return "dup_lines"
    if "min_alpha_words" in p and sum(1 for w in words if _LETTER.search(w)) / max(1, len(words)) < p["min_alpha_words"]:
        return "alpha_words"
    if p.get("stopwords") and len(_EN_STOPWORDS.intersection(w.lower() for w in words)) < p["stopwords"]:
        return "stopwords"
    if "min_hangul" in p and len(_HANGUL.findall(text)) / max(1, len(_LETTER.findall(text))) < p["min_hangul"]:
        return "not_korean"
    return None


def code_reason(text: str, meta: dict, p: dict) -> str | None:
    n = len(text)
    if n < p["min_chars"]:
        return "too_short"
    if n > p["max_chars"]:
        return "too_large"
    lines = text.split("\n")
    if max(map(len, lines)) > p["max_line"]:
        return "long_line"
    if n / len(lines) > p["max_avg_line"]:
        return "avg_line"
    if len(_NOT_ALNUM.sub("", text)) / n < p["min_alnum"]:
        return "low_alnum"
    if any(marker in "\n".join(lines[:5]).lower() for marker in _GENERATED):
        return "generated"
    path = meta.get("path") or ""
    if "." in path and path.rsplit(".", 1)[-1].lower() in _DATA_EXT and n > p["max_data_file"]:
        return "data_file"
    return None


def notebook_text(raw: str) -> str | None:
    def as_dict(x) -> dict:
        return x if isinstance(x, dict) else {}

    try:
        nb = json.loads(raw)
    except ValueError:
        return None
    if not isinstance(nb, dict):
        return None
    meta = as_dict(nb.get("metadata"))
    lang = (as_dict(meta.get("kernelspec")).get("language") or as_dict(meta.get("language_info")).get("name") or "python")
    lang = _FENCE_LANG.sub("", str(lang).lower()) or "python"
    cells = nb.get("cells")
    if not isinstance(cells, list):
        worksheets = nb.get("worksheets")
        cells = [c for ws in worksheets if isinstance(ws, dict) and isinstance(ws.get("cells"), list) for c in ws["cells"]] if isinstance(worksheets, list) else []
    parts, n_code = [], 0
    for cell in cells:
        if not isinstance(cell, dict):
            continue
        src = cell.get("source", cell.get("input", ""))
        src = ("".join(map(str, src)) if isinstance(src, list) else str(src or "")).strip()
        if not src:
            continue
        if cell.get("cell_type") == "code":
            parts.append(f"```{lang}\n{src}\n```")
            n_code += 1
        else:
            parts.append(src)
    return "\n\n".join(parts) if n_code else None


def clean_doc(doc: dict) -> tuple[dict | None, str | None]:
    profile = doc.get("profile", "web")
    meta = doc.get("meta") or {}
    if profile == "code" and (meta.get("language") == "Jupyter Notebook" or str(meta.get("path", "")).endswith(".ipynb")):
        try:
            converted = notebook_text(doc["text"])
        except Exception:
            converted = None
        if converted is None:
            return None, "bad_notebook"
        doc["text"] = converted
    text = normalize(doc["text"], profile)
    p = PROFILES[profile]
    reason = code_reason(text, meta, p) if profile == "code" else text_reason(text, p)
    if reason:
        return None, reason
    doc["text"] = text
    return doc, None
